#include <stdio.h>

int main(void){
    int i = 0;
    int j = 0;
    double cur = 1.0;
    double sum = 0.0;
    while(scanf("%d",&j)==EOF);
    for(; i < j; i++){
        double n = 1 / cur;
        if(i % 2)
            sum -= n;
        else
            sum += n;
        cur *= 2;
    }
    printf("%f\n", sum);
    return 0;    
}

